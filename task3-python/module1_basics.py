# =====================================================================
# Упражнение 3. Стоимость заказа
# =====================================================================
# Демонстрация преобразования ввода в целые числа и арифметики

print("--- Упражнение 3: Стоимость заказа ---")
item_price = int(input("Введите цену товара (руб.): "))
item_quantity = int(input("Введите количество товара (шт.): "))

total_order_cost = item_price * item_quantity
print(f"Итоговая стоимость вашего заказа составляет: {total_order_cost} руб.")
print()


# =====================================================================
# Упражнение 5. Конвертер валюты
# =====================================================================
# Демонстрация работы с типом float и округления результатов

print("--- Упражнение 5: Конвертер валюты ---")
usd_exchange_rate = float(input("Введите текущий курс доллара к рублю: "))
rubles_amount = float(input("Введите сумму в рублях для конвертации: "))

# Рассчитываем сумму и округляем до 2 знаков после запятой с помощью round()
dollars_amount = round(rubles_amount / usd_exchange_rate, 2)
print(f"Сумма в долларах: ${dollars_amount}")
print()


# =====================================================================
# Упражнение 6. Прибыль и рентабельность
# =====================================================================
# Демонстрация сложных расчетов и вывода процентных значений

print("--- Упражнение 6: Прибыль и рентабельность ---")
company_revenue = float(input("Введите общую выручку компании (руб.): "))
company_expenses = float(input("Введите общие затраты компании (руб.): "))

# Вычисляем финансовые показатели
company_profit = company_revenue - company_expenses
profitability_rate = (company_profit / company_revenue) * 100

print(f"Чистая прибыль компании: {company_profit} руб.")
# Округляем рентабельность до 2 знаков для красивого вывода
print(f"Рентабельность бизнеса: {round(profitability_rate, 2)}%")
print()
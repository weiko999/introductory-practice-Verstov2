# Упражнение 2. Категория бизнеса
# =====================================================================
# Демонстрация многоуровневого ветвления if / elif / else

print("--- Упражнение 2: Категория бизнеса ---")
revenue = float(input("Введите годовую выручку компании (руб.): "))

if revenue <= 0:
    print("Выручка должна быть больше нуля.")
elif revenue <= 1000000:
    print("Категория: Микробизнес")
elif revenue <= 10000000:
    print("Категория: Малый бизнес")
elif revenue <= 100000000:
    print("Категория: Средний бизнес")
else:
    print("Категория: Крупный бизнес")
print()


# =====================================================================
# Упражнение 3. Расчёт НДФЛ
# =====================================================================
# Расчет прогрессивной налоговой ставки на основе условий

print("--- Упражнение 3: Расчёт НДФЛ ---")
salary = float(input("Введите размер заработной платы (руб.): "))

if salary <= 50000:
    tax_rate = 0.13
else:
    tax_rate = 0.15

calculated_tax = salary * tax_rate
net_salary = salary - calculated_tax

print(f"Применяемая ставка налога: {int(tax_rate * 100)}%")
print(f"Сумма налога к удержанию: {round(calculated_tax, 2)} руб.")
print(f"Сумма к выдаче на руки: {round(net_salary, 2)} руб.")
print()



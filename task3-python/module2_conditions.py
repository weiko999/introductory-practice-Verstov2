# Упражнение 5. Анализ цен
# =====================================================================
# Использование цикла for для итерации по списку и фильтрации условий

print("--- Упражнение 5: Анализ цен ---")
prices_list = [150.0, 420.5, 290.0, 500.0, 95.9]
print("Анализ фиксированного списка цен:")

for current_price in prices_list:
    if current_price > 300:
        print(f"Цена: {current_price} руб. — ДОРОГО")
    else:
        print(f"Цена: {current_price} руб.")
print()


# =====================================================================
# Упражнение 6. Рост вклада по годам
# =====================================================================
# Моделирование сложного процента с фиксацией изменений на каждом шаге цикла

print("--- Упражнение 6: Рост вклада по годам ---")
initial_capital = float(input("Введите начальную сумму вклада (руб.): "))
interest_rate = float(input("Введите процентную ставку (%): "))

current_balance = initial_capital
# range(1, 6) создает последовательность от 1 до 5 включительно
for year in range(1, 6):
    current_balance += current_balance * (interest_rate / 100)
    print(f"Год {year}: сумма на счете составляет {round(current_balance, 2)} руб.")
print()


# =====================================================================
# Упражнение 9. Выручка за полгода
# =====================================================================
# Динамический сбор данных в цикле, вычисление агрегированных показателей

print("--- Упражнение 9: Выручка за полгода ---")
monthly_revenues = []

# Запускаем цикл 6 раз для сбора данных по каждому месяцу
for month_index in range(1, 7):
    monthly_data = float(input(f"Введите выручку за {month_index}-й месяц (руб.): "))
    monthly_revenues.append(monthly_data)

# Вычисляем агрегированные метрики по собранному списку
minimum_revenue = min(monthly_revenues)
maximum_revenue = max(monthly_revenues)
average_revenue = sum(monthly_revenues) / len(monthly_revenues)

print("\n--- Финансовые итоги за 6 месяцев ---")
print(f"Минимальная выручка: {minimum_revenue} руб.")
print(f"Максимальная выручка: {maximum_revenue} руб.")
print(f"Средняя ежемесячная выручка: {round(average_revenue, 2)} руб.")
print()